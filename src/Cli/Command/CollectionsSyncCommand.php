<?php

declare(strict_types=1);

namespace AtarCms\Cli\Command;

use AtarCms\Cli\AsCommand;
use AtarCms\Cli\CliException;
use AtarCms\Cli\Command;
use AtarCms\Cli\Input;
use AtarCms\Cli\Output;
use AtarCms\Content\IndexedColumns;
use AtarCms\Database\Migrator;
use AtarCms\Kernel\Clock;
use AtarCms\Kernel\Paths;
use DateTimeImmutable;
use DateTimeZone;

#[AsCommand('collections:sync', 'Write a site migration for added, changed or removed ->indexed() fields')]
final class CollectionsSyncCommand implements Command
{
    public function __construct(
        private readonly IndexedColumns $columns,
        private readonly Migrator $migrator,
        private readonly Paths $paths,
        private readonly Clock $clock,
    ) {}

    public function run(Input $input, Output $output): int
    {
        if ($this->migrator->pending() !== []) {
            throw new CliException('There are pending migrations; apply them first with "bin/atar migrate"');
        }
        $statements = $this->columns->statements();
        if ($statements === []) {
            $output->line('Indexed columns are up to date.');

            return 0;
        }

        $directory = $this->paths->migrations();
        if (!is_dir($directory) && !mkdir($directory, 0775, true) && !is_dir($directory)) {
            throw new CliException(sprintf('Cannot create %s', $directory));
        }
        $id = $this->timestamp()->format('Y_m_d_His') . '_sync_collections';
        $file = $directory . '/' . $id . '.php';
        if (file_exists($file)) {
            throw new CliException(sprintf('%s already exists; run the command again in a second', $file));
        }
        if (file_put_contents($file, self::migration($statements)) === false) {
            throw new CliException(sprintf('Cannot write %s', $file));
        }
        $output->line(sprintf('Created database/migrations/%s.php; apply it with "bin/atar migrate".', $id));

        return 0;
    }

    /**
     * The clock time, but at least one second after the latest discovered migration, so that the new
     * migration always runs after the core migrations that create the entries table.
     */
    private function timestamp(): DateTimeImmutable
    {
        $utc = new DateTimeZone('UTC');
        $now = $this->clock->now()->setTimezone($utc);
        $ids = array_keys($this->migrator->discover());
        $latest = $ids === [] ? false : DateTimeImmutable::createFromFormat('!Y_m_d_His', substr((string) end($ids), 0, 17), $utc);
        if ($latest === false) {
            return $now;
        }
        $next = $latest->modify('+1 second');

        return $next > $now ? $next : $now;
    }

    /**
     * @param list<string> $statements
     */
    private static function migration(array $statements): string
    {
        return implode("\n", [
            '<?php',
            '',
            'declare(strict_types=1);',
            '',
            '// Generated by "bin/atar collections:sync" for the ->indexed() fields in config/collections.php.',
            '',
            'use AtarCms\Database\Connection;',
            'use AtarCms\Database\Migration;',
            '',
            'return new class implements Migration {',
            '    public function up(Connection $db): void',
            '    {',
            ...array_map(static fn(string $sql): string => '        $db->execute(' . var_export($sql, true) . ');', $statements),
            '    }',
            '};',
            '',
        ]);
    }
}
